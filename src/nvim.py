#!/usr/bin/env python3
"""Generate the Neovim palette and the dashboard emblem art from palette.json.

usage: [GOT_VARIANT=kurosawa] nvim.py [ROOT]
  -> dotfiles/nvim/lua/got/palette[_kurosawa].lua, enso[_kurosawa].lua,
     lua/lualine/themes/<colorscheme>.lua and colors/<colorscheme>.lua
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from palette import ANSI, C, NAME, SLUG, VARIANT  # noqa: E402
import halfblock  # noqa: E402

ROOT = sys.argv[1] if len(sys.argv) > 1 else os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "dotfiles", "nvim", "lua", "got")


def lua_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    os.makedirs(OUT, exist_ok=True)
    w = max(len(k) for k in C)
    body = "\n".join(f"  {k:<{w}} = \"{v}\"," for k, v in C.items())
    term = ", ".join(f'"{x}"' for x in ANSI)
    mod = "" if VARIANT == "red" else f"_{VARIANT}"
    with open(os.path.join(OUT, f"palette{mod}.lua"), "w") as f:
        f.write(f"-- {NAME}: generated from palette.json by src/nvim.py\nreturn {{\n{body}\n  terminal = {{ {term} }},\n}}\n")
    lines, spans, groups = halfblock.lua_art(30)
    out = ["-- generated by src/nvim.py: half-block render of the ensō emblem", "return {", "  lines = {"]
    out += [f"    {lua_str(x)}," for x in lines]
    out += ["  },", "  hl = {"]
    for sp in spans:
        out.append("    { " + ", ".join(f'{{ "{g}", {a}, {b} }}' for g, a, b in sp) + " },")
    out += ["  },", "  groups = {"]
    for g, spec in sorted(groups.items()):
        out.append(f"    {g} = {{ " + ", ".join(f'{k} = "{v}"' for k, v in spec.items()) + " },")
    out += ["  },", "}", ""]
    with open(os.path.join(OUT, f"enso{mod}.lua"), "w") as f:
        f.write("\n".join(out))
    nv = os.path.join(ROOT, "dotfiles", "nvim")
    os.makedirs(os.path.join(nv, "colors"), exist_ok=True)
    os.makedirs(os.path.join(nv, "lua", "lualine", "themes"), exist_ok=True)
    with open(os.path.join(nv, "colors", f"{SLUG}.lua"), "w") as f:
        f.write(f'require("got").load("{VARIANT}")\n')
    with open(os.path.join(nv, "lua", "lualine", "themes", f"{SLUG}.lua"), "w") as f:
        f.write(LUALINE.replace("got.palette", f"got.palette{mod}"))
    print(f"wrote palette{mod}.lua, enso{mod}.lua, colors/{SLUG}.lua, lualine/themes/{SLUG}.lua")


LUALINE = """-- generated by src/nvim.py
local c = require("got.palette")

return {
  normal = {
    a = { fg = c.paper_hi, bg = c.lacquer, gui = "bold" },
    b = { fg = c.paper, bg = c.stone },
    c = { fg = c.mist, bg = c.ash },
  },
  insert = { a = { fg = c.ink, bg = c.moss, gui = "bold" }, b = { fg = c.paper, bg = c.stone } },
  visual = { a = { fg = c.ink, bg = c.gold, gui = "bold" }, b = { fg = c.paper, bg = c.stone } },
  replace = { a = { fg = c.ink, bg = c.ember, gui = "bold" }, b = { fg = c.paper, bg = c.stone } },
  command = { a = { fg = c.ink, bg = c.sky, gui = "bold" }, b = { fg = c.paper, bg = c.stone } },
  terminal = { a = { fg = c.ink, bg = c.jade, gui = "bold" }, b = { fg = c.paper, bg = c.stone } },
  inactive = {
    a = { fg = c.smoke, bg = c.ash },
    b = { fg = c.smoke, bg = c.ash },
    c = { fg = c.smoke, bg = c.ash },
  },
}
"""


if __name__ == "__main__":
    main()
